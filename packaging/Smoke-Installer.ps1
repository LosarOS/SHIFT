[CmdletBinding()]
param([ValidatePattern('^\d+\.\d+\.\d+(?:-rc\.\d+)?$')][string]$Version='1.0.0-rc.5')
$ErrorActionPreference='Stop'
Set-StrictMode -Version Latest
if($env:GITHUB_ACTIONS -ne 'true'){throw 'Installer smoke requires a disposable GitHub Actions Windows runner.'}
$repo=Split-Path $PSScriptRoot -Parent
$out=Join-Path $repo 'artifacts'
$install=Join-Path $out 'installed-smoke'
$setup=Join-Path $out "SHIFT-$Version-win-x64-setup.exe"
$uninstallKey='HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\{E4FAF163-A081-42F6-9974-0729E1397AA3}_is1'
if(Test-Path $uninstallKey){throw 'Refusing to replace an existing SHIFT installation.'}
$data=Join-Path $env:LOCALAPPDATA 'SHIFT'
$owner=[guid]::NewGuid()
$ownerFile=Join-Path $data '.shift-ci-owner'
if(Test-Path $data){throw 'Refusing to use an existing SHIFT user profile.'}
if(Test-Path $install){throw 'Refusing to replace an existing test installation directory.'}
function Install-Candidate {
    $process=Start-Process $setup -ArgumentList @('/VERYSILENT','/SUPPRESSMSGBOXES','/NORESTART','/SP-',"/DIR=`"$install`"") -Wait -PassThru
    try { if($process.ExitCode -ne 0){throw "Installer exited $($process.ExitCode)"} } finally { $process.Dispose() }
    if(-not(Test-Path (Join-Path $install 'SHIFT.exe'))){throw 'Installed executable missing.'}
    if(-not(Test-Path (Join-Path ([Environment]::GetFolderPath('Programs')) 'SHIFT.lnk'))){throw 'Start Menu shortcut missing.'}
}
function Remove-Candidate {
    $uninstaller=Join-Path $install 'unins000.exe'
    if(Test-Path $uninstaller){
        $process=Start-Process $uninstaller -ArgumentList @('/VERYSILENT','/SUPPRESSMSGBOXES','/NORESTART') -Wait -PassThru
        try { if($process.ExitCode -ne 0){throw 'Uninstall failed.'} } finally { $process.Dispose() }
    }
    if(Test-Path $uninstallKey){throw 'Uninstall registry key remains.'}
    if(Test-Path (Join-Path $install 'SHIFT.exe')){throw 'Executable remains after uninstall.'}
}
function Assert-OwnedData([string]$ExpectedHash) {
    if(-not(Test-Path $ownerFile) -or (Get-Content $ownerFile -Raw).Trim() -ne $owner.ToString()){throw 'Test data ownership changed.'}
    $database=Join-Path $data 'shift.db'
    if(-not(Test-Path $database) -or (Get-FileHash $database -Algorithm SHA256).Hash -ne $ExpectedHash){throw 'Installer modified or removed the saved SQLite database.'}
}
try {
    Install-Candidate
    & powershell.exe -NoProfile -File (Join-Path $PSScriptRoot 'Smoke-Windows.ps1') -AppDirectory $install -Installed -DataOwner $owner -PreserveData -DiagnosticsDirectory (Join-Path $out 'diagnostics')
    if($LASTEXITCODE -ne 0){throw 'Installed application UI smoke failed.'}
    $hash=(Get-FileHash (Join-Path $data 'shift.db') -Algorithm SHA256).Hash
    # Reinstall over the existing version exercises Inno's upgrade data-preservation path.
    Install-Candidate
    Assert-OwnedData $hash
    Remove-Candidate
    Assert-OwnedData $hash
    Install-Candidate
    Assert-OwnedData $hash
    & powershell.exe -NoProfile -File (Join-Path $PSScriptRoot 'Smoke-Windows.ps1') -AppDirectory $install -Installed -DataOwner $owner -ResumeOwnedData -PreserveData -DiagnosticsDirectory (Join-Path $out 'diagnostics-reinstall')
    if($LASTEXITCODE -ne 0){throw 'Reinstalled application failed to load saved data.'}
    $hash=(Get-FileHash (Join-Path $data 'shift.db') -Algorithm SHA256).Hash
    Remove-Candidate
    Assert-OwnedData $hash
    @{schema_version=1;status='passed';version=$Version;environment='disposable-windows-ui-automation';checks=@('per_user_install','start_menu_shortcut','installed_ui','in_place_same_version_reinstall','uninstall','registry_cleanup','reinstall','saved_workspace_settings','sqlite_sha256_preservation');manual_acceptance=$false} |
        ConvertTo-Json -Depth 4 | Set-Content (Join-Path $out 'diagnostics/installer-smoke.json')
    Write-Host 'Installer smoke passed: install, shortcut, UI flow/restart, in-place reinstall, uninstall, reinstall with saved workspace/settings, SQLite preservation.'
} finally {
    Remove-Candidate
    # This token was generated by this script. Never remove unowned user profiles.
    if((Test-Path $ownerFile) -and (Get-Content $ownerFile -Raw).Trim() -eq $owner.ToString()) { Remove-Item $data -Recurse -Force }
}
